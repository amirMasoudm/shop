// اصلاحِ مشخصاتِ فنیِ آنتن‌هایِ خانوادهٔ SP62 (برندِ WimaxNear) در فروشگاه
//
// منبع: برگه‌هایِ مشخصاتِ رسمیِ خودِ WimaxNear که مالک فرستاد
//        (SP62-27D · SP62-28D · SP62-32D · SP62-34.5D-Ultra-HP · SP62-35D)
//        + دو صفحهٔ کاتالوگِ شرکت (ص۹ سریِ High Performance، ص۱۰ سریِ پهن‌باند)
//
// سه خطایِ اثبات‌شده که اصلاح می‌شود:
//   ۱) کانکتور «2× SMA مادگی» → «۲ × N-Female». هر چهار برگه N-Female دارند و
//      SMA برایِ دیشِ ۱۰۰ واتی اصلاً منطقی نیست (خریدار پیگتیلِ اشتباه می‌گیرد).
//   ۲) باندِ «5.1–5.9 GHz» → «۴۸۰۰ تا ۶۲۰۰ مگاهرتز». باندِ ثبت‌شده کوچک‌تر از
//      باندِ واقعیِ محصول بود.
//   ۳) برندِ «نیر (Nira)» → «WimaxNear». کدِ قطعهٔ SP62-xx و لوگویِ رویِ هر برگه.
//
// ⚠️ محافظه‌کاری: «مشخصاتِ خانوادگی» (که رویِ هر چهار برگه یکسان است) به همهٔ
//    محصولات اعمال می‌شود، ولی عددهایِ مدل‌به‌مدل (بهره، قطر، وزن، پهنایِ پرتو)
//    فقط جایی نوشته می‌شود که برگهٔ همان مدل را داشته باشیم. مدل‌هایی که برگه‌شان
//    را نداریم (30D, 33D, 35D, XD, L) دست‌نخورده می‌مانند جز همان سه خطایِ بالا.
//    همچنین باندِ محصولاتی که از قبل عددِ درست و متفاوتی دارند بازنویسی نمی‌شود.
// ─────────────────────────────────────────────────────────────────────────────

// مقادیرِ پیش از اصلاح (برایِ بازگردانیِ دستی، چون اجرایِ اول پشتیبان نگرفت):
//   هفت محصولِ قدیمیِ 6a5cbd… :  باند «5.1–5.9 GHz» · کانکتور «2× SMA مادگی» · برند «نیر (Nira)»
//   6a9473cf…59c و …59d      :  باند «۵٫۱ تا ۵٫۹ گیگاهرتز» · بدونِ کانکتور
//   6a9473cf…59e             :  باند «۴۷۰۰ تا ۶۴۰۰ مگاهرتز» · کانکتور «N مادگی»  (فقط برند عوض شد)
//   6a9473cf…59f             :  باند «۴۸۰۰ تا ۶۱۰۰ مگاهرتز» · کانکتور «N مادگی»  (فقط برند عوض شد)

const G = 'آنتن';

// مشخصاتی که رویِ همهٔ برگه‌هایِ خانوادهٔ SP62 یکسان است
const FAMILY = [
  ['برند', 'WimaxNear'],
  ['نوع', 'دیش پارابولیک دوپلاریته (Dual Polarity)'],
  ['پلاریزاسیون', 'خطی، دوگانه (V و H)'],
  ['کانکتور', '۲ × N-Female'],
  ['امپدانس', '۵۰ اهم'],
  ['توان ورودی', '۱۰۰ وات'],
  ['استاندارد لوب کناری', 'ETSI EN 302.326-3 DN1-DN5'],
  ['تحمل باد', '۲۰۰ کیلومتر بر ساعت'],
  ['جنس بدنه', 'آلیاژ آلومینیوم']
];

// باندِ پیش‌فرضِ خانواده — فقط جایگزینِ باندِ غلطِ «۵٫۱ تا ۵٫۹» می‌شود
const BAND = '۴۸۰۰ تا ۶۲۰۰ مگاهرتز (۴٫۸ تا ۶٫۲ گیگاهرتز)';
const BAND_IS_WRONG = /5\.1|۵٫۱|5\.9|۵٫۹/;

// عددهایِ مدل‌به‌مدل — فقط برایِ مدل‌هایی که برگهٔ رسمیِ همان مدل را داریم
const PER_MODEL = {
  '27D': [
    ['بهره', '۲۵٫۲ تا ۲۷٫۷ dBi (در سراسرِ باند)'],
    ['پهنای پرتو ۳dB', '۸ درجه'],
    ['قطر دیش', '۴۵ سانتی‌متر'],
    ['وزن', '۳ کیلوگرم'],
    ['نسبت جلو به عقب', '‎−۳۶ dB'],
    ['جدایش پلاریته', '‎−۲۸ dB'],
    ['VSWR', '1.7:1 (typ)']
  ],
  '32D': [
    ['بهره', '۳۰٫۲ تا ۳۲٫۲ dBi (در سراسرِ باند)'],
    ['پهنای پرتو ۳dB', '۴٫۱ درجه'],
    ['قطر دیش', '۸۰ سانتی‌متر'],
    ['وزن', '۶٫۵ کیلوگرم'],
    ['نسبت جلو به عقب', '‎−۴۰ dB'],
    ['جدایش پلاریته', '‎−۳۰ dB'],
    ['VSWR', '1.7:1 (typ)']
  ]
};

// کدام محصول به کدام برگه وصل است (بر اساسِ فیلدِ «مدل»ِ خودِ محصول)
function datasheetKey(modelValue) {
  if (!modelValue) return null;
  const m = String(modelValue);
  if (/\b27D\b/.test(m)) return '27D';
  // «32dBi» و «SP62-32D» و «SP62-32D-HP» همگی به برگهٔ 32D می‌خورند
  if (/32D|32dBi/i.test(m)) return '32D';
  return null;
}

const products = db.products.find({
  $or: [{ name: /نیر/ }, { name: /SP62/i } ]
}).toArray();

const before = [];
let touched = 0, rows = 0;

for (const p of products) {
  const specs = p.techSpecs || [];
  if (!specs.length) continue;                   // بسته‌های تعلیقی/بی‌مشخصات

  before.push({ _id: p._id, name: p.name, techSpecs: JSON.parse(JSON.stringify(specs)) });

  const get = k => specs.find(s => s.key === k);
  const set = (k, v) => {
    const r = get(k);
    if (r) { if (r.value !== v) { r.value = v; rows++; } }
    else { specs.push({ group: G, key: k, value: v }); rows++; }
  };

  const model = (get('مدل') || {}).value;

  // ۱) مشخصاتِ خانوادگی
  FAMILY.forEach(([k, v]) => set(k, v));

  // ۲) باند — فقط اگر عددِ ثبت‌شده همان ۵٫۱–۵٫۹ غلط باشد
  const band = get('باند فرکانسی');
  if (!band || BAND_IS_WRONG.test(band.value)) set('باند فرکانسی', BAND);

  // ۳) عددهایِ مدل‌به‌مدل، فقط با برگهٔ همان مدل
  const key = datasheetKey(model);
  if (key) PER_MODEL[key].forEach(([k, v]) => set(k, v));

  db.products.updateOne({ _id: p._id }, { $set: { techSpecs: specs } });
  touched++;
}

print('محصولِ اصلاح‌شده: ' + touched + '   ردیفِ تغییرکرده/افزوده: ' + rows);
print('نسخهٔ پیش از تغییر در کالکشنِ _backup_wimaxnear_specs ذخیره شد.');
// ⚠️ نامِ کالکشن با _ شروع می‌شود، پس dot-notation در mongosh کار نمی‌کند —
// حتماً getCollection. (اجرایِ اولِ ۱۴۰۵/۰۶/۱۴ به همین دلیل پشتیبان نگرفت.)
db.getCollection('_backup_wimaxnear_specs').drop();
if (before.length) db.getCollection('_backup_wimaxnear_specs').insertMany(before);

print('─────────────────────────────────');
