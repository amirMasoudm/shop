package org.example.shop1.model.service;

import java.util.Map;

/**
 * پخشِ رویدادِ زنده به مشترکانِ یک گفت‌وگو.
 * <p>
 * ⚠️ <b>چرا اینترفیس، وقتی فقط یک پیاده‌سازی دارد؟</b> پیاده‌سازیِ فعلی
 * ({@code LocalMessageBroadcaster}) درون‌حافظه‌ای و <b>تک‌نودی</b> است و برای امروز
 * کافی است. ولی اگر روزی دو نمونه از بک‌اند بالا بیاید، پیامِ کاربرِ روی نودِ ۱ به
 * کارشناسِ روی نودِ ۲ نمی‌رسد و هیچ خطایی هم دیده نمی‌شود — فقط پیام‌ها بی‌صدا گم
 * می‌شوند. راهِ حلِ آن روز Redis pub/sub است؛ این مرز هست تا آن روز یک پیاده‌سازیِ
 * تازه جای این یکی بنشیند، نه اینکه لایهٔ چت بازنویسی شود.
 */
public interface MessageBroadcaster {

    /** ارسالِ یک پاکتِ JSON به همهٔ اتصال‌هایِ بازِ یک گفت‌وگو. */
    void broadcast(String conversationId, Map<String, Object> payload);

    /**
     * ارسال به همهٔ کارشناسانِ آنلاین، مستقل از گفت‌وگو — برایِ تازه‌کردنِ صفِ مشترک
     * وقتی گفت‌وگویی تازه می‌آید یا کسی تصاحبش می‌کند.
     */
    void broadcastToAgents(Map<String, Object> payload);
}
