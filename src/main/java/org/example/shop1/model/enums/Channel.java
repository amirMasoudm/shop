package org.example.shop1.model.enums;

/**
 * کانالِ ورودِ بازدیدکننده — مشتق‌شده از ارجاع‌دهنده و UTM، نه ورودیِ خام.
 * <p>
 * ⚠️ {@code DIRECT} یعنی <b>«نامعلوم»</b>، نه «آدرس را تایپ کرده». مرورگرِ داخلیِ
 * تلگرام و اینستاگرام معمولاً هدرِ ارجاع نمی‌فرستند و سیاست‌های {@code Referrer-Policy}
 * هم آن را حذف می‌کنند. برچسبِ پنل در فازِ ۲ باید همین را بگوید، وگرنه روی عددی
 * تصمیم می‌گیریم که معنایش را اشتباه فهمیده‌ایم.
 */
public enum Channel {

    /** بدونِ ارجاع‌دهنده و بدونِ UTM — یعنی نامعلوم. */
    DIRECT,

    ORGANIC_SEARCH,

    /** {@code utm_medium} برابرِ cpc/ppc، یا وجودِ {@code gclid}. */
    PAID,

    SOCIAL,

    /**
     * ترب، ایمالز و مشابه. عمداً از {@link #REFERRAL} جداست چون فیدِ ترب داریم؛
     * اگر داخلِ «ارجاع» گم شود هیچ‌وقت نمی‌فهمیم آن فید چقدر می‌فروشد — و این تنها
     * کانالی است که هزینهٔ مستقیم دارد.
     */
    MARKETPLACE,

    /** هر دامنهٔ بیرونیِ دیگر. */
    REFERRAL
}
