package org.example.shop1.model.enums;


public enum Role {
    ADMIN,
    USER,

    /**
     * کارشناسِ ارشد — همان دسترسیِ کارشناسِ فروش‌وقیمت‌گذاری (SALES) به‌اضافه‌ی
     * دسترسیِ محصول: می‌تواند قیمت‌ها/پرچمِ فروش/کفِ قیمتِ رقبا (شاملِ فیلدِ
     * «فروش تعدادی») را تغییر دهد و محصول اضافه/ویرایش/حذف کند
     * (/api/v1/products/admin/**، POST/PUT/DELETEِ /api/v1/products/**).
     */
    PRICER,

    /**
     * کارشناسِ فروش و قیمت‌گذاری — دقیقاً مثلِ PRICER در میزِ کارِ قیمت‌گذاری
     * (شاملِ فیلدِ «فروش تعدادی»)، فقط بدونِ دسترسیِ محصول.
     */
    SALES,

    /**
     * کارشناسِ فروش — فقط مشاهده‌یِ میزِ کارِ قیمت‌گذاری/موجودی، بدونِ هیچ حقِ
     * نوشتنی (نه قیمت، نه «فروش تعدادی») و بدونِ دسترسیِ محصول.
     */
    SUPPORT
}
