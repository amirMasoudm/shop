package org.example.shop1.model.enums;


public enum Role {
    ADMIN,
    USER,

    /**
     * کارشناسِ کاملِ قیمت‌گذاری (۱ نفر) — قیمت‌ها، پرچمِ فروش و کفِ قیمتِ رقبا را
     * می‌بیند و تغییر می‌دهد. موجودی برایش هم فقط-خواندنی است (طبقِ مرزِ فازِ ۱).
     */
    PRICER,

    /**
     * کارشناسِ فروش (۵ نفر) — میزِ کار را فقط می‌خواند؛ هیچ نوشتنی ندارد.
     */
    SALES,

    /**
     * نقشِ قدیمی و بلااستفاده (هیچ کاربری ندارد). عمداً حذف نشد تا رکوردِ احتمالیِ
     * قدیمی موقعِ خواندن خطا ندهد؛ برایِ کاربرانِ جدید از SALES استفاده شود.
     */
    SUPPORT,

    /**
     * کارشناسِ محصولات — فقط تبِ محصولاتِ SalesPanel.html (همان مارک‌آپ/منطقِ تبِ
     * محصولاتِ پنلِ ادمین). دسترسی‌اش کمینه است: /api/v1/products/admin/** و
     * POST/PUT/DELETEِ /api/v1/products/**؛ به بنر/دوره/مقاله/تنظیمات/آرشیوِ آموزش
     * و به‌خودِ /Admin.html دسترسی ندارد.
     */
    PRODUCT_EDITOR
}
