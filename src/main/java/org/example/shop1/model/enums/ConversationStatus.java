package org.example.shop1.model.enums;

/** وضعیتِ گفت‌وگوی پشتیبانی. */
public enum ConversationStatus {

    /** تصاحب‌نشده — در صفِ مشترک است و همهٔ کارشناسان می‌بینندش. */
    OPEN,

    /** یک کارشناس تصاحبش کرده؛ از صفِ بقیه بیرون رفته است. */
    ASSIGNED,

    /** بسته‌شده. گفت‌وگو حذف نمی‌شود — تاریخچه به‌ازای هر مشتری پیوسته می‌ماند. */
    CLOSED
}
